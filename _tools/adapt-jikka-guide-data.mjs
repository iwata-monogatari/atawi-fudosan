function conciseSupplement(value, page) {
  let text = String(value || '未確認事項を一つ選び、担当と期限を決める')
    .replace(/^「[^」]+」では、/, '').replace(/^今回確認したいこと[:：]\s*/, '')
    .replace(/[「」]/g,'').trim();
  if (text.length>136) text = `${text.slice(0,136).replace(/[、,][^、,]*$/,'')}…`;
  return text;
}

