import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const excluded = new Set(['.git', '.wrangler', 'node_modules', 'docs', 'tests']);
const self = '_tools/check-property-address-policy.mjs';

// Scan both rendered text and raw source (including JSON-LD and escaped LINE text).
export function addressPolicyErrors(source, file = '') {
  const text = source.replace(/\\u([0-9a-f]{4})/gi, (_, hex) => String.fromCharCode(parseInt(hex, 16)))
    .replace(/&#(?:x([0-9a-f]+)|(\d+));/gi, (_, hex, dec) => String.fromCodePoint(parseInt(hex || dec, hex ? 16 : 10)))
    .replace(/<[^>]*>/g, '').replace(/&nbsp;|\s|\\[nr]/g, '');
  const rules = [
    /(?:町名|市町村名|市町村)(?:・字|と字)?(?:まで|だけ)(?:で|でも|の入力で)?(?:大丈夫|十分|OK|ＯＫ|構いません|かまいません|相談できます|お申し込み|申し込め|受付)/i,
    /(?:番地|地番)(?:・地番|や地番|と地番)?(?:は|の入力は|の記入は)?[（(「]?(?:任意|不要|省略可|後日|あとで)/,
    /(?:番地|地番)(?:や地番|・地番)?は、?(?:可否が分かってから|相談後|受付後)/,
    /(?:番地|地番)(?:・地番|や地番)?(?:が|は)?(?:不明|わからな|分からな)[^。！？]{0,24}(?:大丈夫|OK|構いません|相談できます|申し込め)/i,
    /(?:住所|所在地)[（(](?:市町村|町名)[^）)]{0,12}[）)][（(]任意[）)]/,
  ];
  const errors = rules.flatMap(rule => {const match = text.match(rule); return match ? [`${file}: 番地必須に反する案内: ${match[0]}`] : [];});
  if (/\.html$/.test(file)) {
    for (const field of source.matchAll(/<input\b[^>]*>/gi)) {
      if (!/\b(?:id|name)\s*=\s*["'](?:addr|addressDetail|lpAddressDetail)["']/i.test(field[0]) || /\btype\s*=\s*["']hidden["']/i.test(field[0])) continue;
      if (!/\srequired(?:\s|=|\/?>)/i.test(field[0])) errors.push(`${file}: 住所・番地入力欄の required がありません`);
      const prefix = source.slice(0, field.index);
      if (prefix.lastIndexOf('<details') > prefix.lastIndexOf('</details>')) errors.push(`${file}: 住所・番地欄が折りたたみ内にあります`);
    }
  }
  return errors;
}

export function assertAddressPolicy(source, file) {
  const errors = addressPolicyErrors(source, file);
  if (errors.length) throw new Error(errors.join('\n'));
}

function files(dir = root) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    if (excluded.has(entry.name)) return [];
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return files(full);
    const relative = path.relative(root, full).replaceAll('\\', '/');
    return /\.(html|js|mjs|json|py|txt)$/.test(entry.name) && relative !== self ? [relative] : [];
  });
}

export function checkSite() {
  const targets = files();
  const errors = targets.flatMap(file => addressPolicyErrors(fs.readFileSync(path.join(root, file), 'utf8'), file));
  const core = fs.readFileSync(path.join(root, 'assets/property-address-core.mjs'), 'utf8').replace(/^export /gm, '').replace(/\r\n/g, '\n');
  const expected = '// Generated by _tools/build-property-address.mjs; edit the core module.\n(function () {\n' + core + '\nwindow.karteAddress = { addressValid, detailValid, addressMessage };\n})();\n';
  if (fs.readFileSync(path.join(root, 'assets/property-address.js'), 'utf8').replace(/\r\n/g, '\n') !== expected) errors.push('assets/property-address.js: 共通判定の生成元と不一致。node _tools/build-property-address.mjs を実行してください');
  return { errors, count: targets.length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const result = args.length ? { errors: args.flatMap(file => addressPolicyErrors(fs.readFileSync(file, 'utf8'), file)), count: args.length } : checkSite();
  if (result.errors.length) { console.error(result.errors.join('\n')); process.exitCode = 1; }
  else console.log(`Property address policy: ${result.count} files passed.`);
}
