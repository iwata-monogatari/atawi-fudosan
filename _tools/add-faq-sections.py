def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def faq_ld(pairs):
    return '<script type="application/ld+json">' + json.dumps({
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": [{"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in pairs],
    }, ensure_ascii=False, separators=(",", ":")) + "</script>"


def rd(p):
    return open(os.path.join(ROOT, p), "rb").read().decode("utf-8")


changed = []


def wr(p, s):
    changed.append(p)
    if not DRY:
        open(os.path.join(ROOT, p), "wb").write(s.encode("utf-8"))


for rel, (heading, pairs) in AREA_FAQ.items():
    s = rd(rel)
    if '"FAQPage"' in s:
        continue
    section = ('  <section class="section"><div class="wrap"><h2>' + esc(heading) + '</h2><div class="faq">'
               + "".join(f'<details><summary>{esc(q)}</summary><p class="a">{esc(a)}</p></details>' for q, a in pairs)
               + '</div></div></section>\n')
    nl = "\r\n" if "\r\n" in s else "\n"
    anchor = s.find('  <section class="section alt"><div class="wrap"><h2>住所が全部分からなくても始められます')
    if anchor < 0:
        print("anchor not found:", rel)
        continue
    s = s[:anchor] + section.replace("\n", nl) + s[anchor:]
    s = s.replace("</head>", faq_ld(pairs) + nl + "</head>", 1)
    wr(rel, s)

for rel, pairs in ARTICLE_FAQ.items():
    s = rd(rel)
    if '"FAQPage"' in s:
        continue
    section = ('<section class="article-faq"><h2>この記事のよくある質問</h2>'
               + "".join(f"<details><summary>{esc(q)}</summary><p>{esc(a)}</p></details>" for q, a in pairs)
               + "</section>")
    anchor = s.find('<aside class="article-cta">')
    if anchor < 0:
        print("anchor not found:", rel)
        continue
    nl = "\r\n" if "\r\n" in s else "\n"
    s = s[:anchor] + section + s[anchor:]
    s = s.replace("</head>", faq_ld(pairs) + nl + "</head>", 1)
    wr(rel, s)

css = rd("jikka/style.css")
if ".article-faq" not in css:
    wr("jikka/style.css", css.rstrip("\r\n") + "\n" + JIKKA_CSS)

print(("dry-run " if DRY else "") + f"changed {len(changed)} files")
for p in changed:
    print(" ", p)
